using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Ncma.CodeGen;

internal static class ComponentAggregation
{
    private static readonly DiagnosticDescriptor Invalid = new("NCMA009", "Invalid component aggregation",
        "{0}", "Ncma.CodeGen", DiagnosticSeverity.Error, true);

    internal static void Emit(SourceProductionContext context, Compilation compilation, IEnumerable<INamedTypeSymbol> generated)
    {
        bool invalid = false;
        void Reject(string message) { invalid = true; context.ReportDiagnostic(Diagnostic.Create(Invalid, Location.None, message)); }
        var calls = generated.Select(t => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".Generated.Register(registry);").ToList();
        void Scan(INamespaceOrTypeSymbol container)
        {
            foreach (var member in container.GetMembers()) {
                if (member is INamespaceOrTypeSymbol nested) Scan(nested);
                if (member is not IMethodSymbol method || !method.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "Ncma.Runtime.ComponentRegistrationAttribute")) continue;
                if (!method.IsStatic || method.IsGenericMethod || method.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal) ||
                    method.ContainingType.IsGenericType || method.ContainingType.ContainingType is not null ||
                    method.Parameters.Length != 1 || method.Parameters[0].RefKind != RefKind.None || method.Parameters[0].Type.ToDisplayString() != "Ncma.Runtime.ComponentRegistry" ||
                    (!method.ReturnsVoid && method.ReturnType.ToDisplayString() != "Ncma.Runtime.ComponentRegistry")) {
                    Reject("ComponentRegistration requires an accessible static non-generic method (ComponentRegistry), returning void or ComponentRegistry, on a top-level non-generic type."); continue;
                }
                calls.Add(method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".@" + method.Name + "(registry);");
            }
        }
        Scan(compilation.Assembly.GlobalNamespace);
        var dependencies = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols) {
            var attributes = assembly.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "Ncma.Runtime.GeneratedComponentModuleAttribute").ToArray();
            if (attributes.Length > 1) { Reject("Duplicate component module manifest: " + assembly.Name); continue; }
            foreach (var attribute in attributes) {
                if (attribute.ConstructorArguments.Length != 1 || attribute.ConstructorArguments[0].Kind != TypedConstantKind.Type ||
                    attribute.ConstructorArguments[0].Value is not INamedTypeSymbol provider) {
                    Reject("Invalid component module manifest arguments: " + assembly.Name); continue;
                }
                if (!SymbolEqualityComparer.Default.Equals(provider.ContainingAssembly, assembly)) {
                    Reject("Invalid component module manifest ownership: " + assembly.Name); continue;
                }
                var moduleType = compilation.GetTypeByMetadataName("Ncma.Runtime.ComponentModule");
                if (!AccessibleProvider(provider) || moduleType is null ||
                    !provider.GetMembers("Module").OfType<IPropertySymbol>().Any(p => p.IsStatic && !p.IsIndexer && p.Parameters.Length == 0 &&
                        p.DeclaredAccessibility == Accessibility.Public && p.GetMethod?.DeclaredAccessibility == Accessibility.Public &&
                        SymbolEqualityComparer.Default.Equals(p.Type, moduleType))) {
                    Reject("Invalid component module manifest provider: " + assembly.Name); continue;
                }
                dependencies.Add(provider.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".Module");
            }
        }
        if (invalid || (calls.Count == 0 && dependencies.Count == 0)) return;
        string name = compilation.AssemblyName ?? "Assembly";
        string ns = name.Split('.').All(SyntaxFacts.IsValidIdentifier) ? name + ".Generated" : "Ncma.Generated.A" + PortableRuntime.SourceHash(name);
        if (compilation.GetTypeByMetadataName(ns + ".ComponentModule") is { } existing && SymbolEqualityComparer.Default.Equals(existing.ContainingAssembly, compilation.Assembly)) {
            Reject("Reserve generated type " + ns + ".ComponentModule"); return;
        }
        string source = $$"""
            // <auto-generated/>
            #nullable enable
            [assembly: global::Ncma.Runtime.GeneratedComponentModuleAttribute(typeof(global::{{ns}}.ComponentModule))]
            namespace {{ns}};
            public static class ComponentModule
            {
                public static global::Ncma.Runtime.ComponentModule Module { get; } = new(
                    {{Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(compilation.Assembly.Identity.ToString(), true)}},
                    [{{string.Join(", ", dependencies)}}], Register);
                private static void Register(global::Ncma.Runtime.ComponentRegistry registry)
                {
                    {{string.Join("\n        ", calls.OrderBy(c => c, StringComparer.Ordinal))}}
                }
            }
            """;
        context.AddSource("Assembly.ComponentModule.g.cs", source);
    }

    private static bool AccessibleProvider(INamedTypeSymbol provider)
    {
        // typeof(Open<>) is legal metadata but cannot be named by generated consumer code.
        // A public nested provider also needs every containing type to be public/non-generic.
        for (INamedTypeSymbol? type = provider; type is not null; type = type.ContainingType)
            if (type.DeclaredAccessibility != Accessibility.Public || type.IsGenericType || type.IsUnboundGenericType) return false;
        return provider.TypeKind is TypeKind.Class or TypeKind.Struct;
    }
}
