using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Ncma.CodeGen;

[Generator(LanguageNames.CSharp)]
public sealed class ExportGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Invalid = new("NCMA101", "Invalid generated Export declaration", "{0}", "Ncma.CodeGen", DiagnosticSeverity.Error, true);
    private sealed record Field(string Name, uint Kind, string Display, string Category, string Cast);
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName("Ncma.GenerateExportsAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (ctx, _) => (Type: (INamedTypeSymbol)ctx.TargetSymbol, Location: ctx.TargetNode.GetLocation()));
        context.RegisterSourceOutput(types, static (ctx, input) => Emit(ctx, input.Type, input.Location));
    }
    private static void Emit(SourceProductionContext context, INamedTypeSymbol type, Location location)
    {
        void Error(string message) => context.ReportDiagnostic(Diagnostic.Create(Invalid, location, message));
        // Bounded first contract: no inherited/hidden exports, generic/nested types or init-only writes.
        if (type.TypeKind != TypeKind.Class || type.IsRecord || !type.IsSealed || type.IsAbstract || type.Arity != 0 ||
            type.ContainingType is not null || type.DeclaredAccessibility != Accessibility.Public ||
            type.BaseType?.ToDisplayString() != "Ncma.Behaviour" ||
            type.Interfaces.Any(i => i.ToDisplayString() == "Ncma.IGeneratedExportSource") ||
            !type.DeclaringSyntaxReferences.All(r => r.GetSyntax() is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.PartialKeyword)) ||
            !type.InstanceConstructors.Any(c => c.DeclaredAccessibility == Accessibility.Public && c.Parameters.Length == 0) ||
            type.GetMembers().OfType<IPropertySymbol>().Any(p => p.IsRequired) || type.GetMembers().OfType<IFieldSymbol>().Any(f => f.IsRequired)) {
            Error("Use a public sealed partial non-generic top-level class directly deriving Behaviour with a public parameterless constructor and no required members or manual generated interface."); return;
        }
        if (Encoding.UTF8.GetByteCount(type.ToDisplayString()) >= 512) { Error("Behaviour type name exceeds the existing 512-byte budget."); return; }
        var fields = new List<Field>();
        foreach (var member in type.GetMembers().OrderBy(m => m.Name, StringComparer.Ordinal)) {
            var attribute = member.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Ncma.ExportAttribute");
            if (attribute is null) continue;
            ITypeSymbol? valueType = member switch {
                IFieldSymbol f when !f.IsStatic && !f.IsReadOnly && !f.IsConst && f.DeclaredAccessibility == Accessibility.Public => f.Type,
                IPropertySymbol p when !p.IsStatic && !p.IsIndexer && !p.ReturnsByRef && !p.ReturnsByRefReadonly &&
                    p.GetMethod?.DeclaredAccessibility == Accessibility.Public && p.SetMethod?.DeclaredAccessibility == Accessibility.Public && !p.SetMethod.IsInitOnly => p.Type,
                _ => null
            };
            (uint kind, string cast) = valueType?.SpecialType switch {
                SpecialType.System_Single => (1u, "float"), SpecialType.System_Double => (2u, "double"),
                SpecialType.System_Int32 => (3u, "int"), SpecialType.System_Boolean => (4u, "bool"), _ => (0u, "")
            };
            if (kind == 0) { Error("Export '" + member.Name + "' must be a public writable instance float/double/int/bool field or property (no init-only/ref/indexer)."); return; }
            string display = attribute.NamedArguments.FirstOrDefault(p => p.Key == "DisplayName").Value.Value as string ?? member.Name;
            string category = attribute.NamedArguments.FirstOrDefault(p => p.Key == "Category").Value.Value as string ?? "Gameplay";
            if (new[] { member.Name, display, category }.Any(s => Encoding.UTF8.GetByteCount(s) >= 128)) { Error("Export metadata exceeds the existing 128-byte budget."); return; }
            fields.Add(new(member.Name, kind, display, category, cast));
        }
        if (fields.Count > 1024 || fields.Select(f => f.Name).Distinct(StringComparer.Ordinal).Count() != fields.Count) { Error("Duplicate Export names or more than 1024 exports."); return; }
        string full = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        static string Quote(string s) => SymbolDisplay.FormatLiteral(s, true);
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace) code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(";\n");
        code.Append("public sealed partial class @").Append(type.Name).Append(" : global::Ncma.IGeneratedExportSource\n{\n    global::Ncma.GeneratedExportBinding[] global::Ncma.IGeneratedExportSource.DescribeGeneratedExports() => [\n");
        foreach (var f in fields) {
            string access = "((" + full + ")instance).@" + f.Name;
            string read = f.Kind == 4 ? access + " ? 1d : 0d" : "(double)" + access;
            string checkedValue = "global::Ncma.ExportNumbers.Require(number, " + f.Kind + "u)";
            string write = f.Kind == 4 ? checkedValue + " != 0" : "(" + f.Cast + ")" + checkedValue;
            code.Append("        new(").Append(Quote(f.Name)).Append(", ").Append(f.Kind).Append("u, ").Append(Quote(f.Display)).Append(", ").Append(Quote(f.Category))
                .Append(", static instance => ").Append(read).Append(", static (instance, number) => ").Append(access).Append(" = ").Append(write).Append("),\n");
        }
        code.Append("    ];\n}\n");
        string hint = PortableRuntime.SourceHash(full) + ".Exports.g.cs";
        context.AddSource(hint, code.ToString());
    }
}
