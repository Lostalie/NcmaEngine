// Build-host tool only. No runtime compiler or bytecode-file fallback in NcmaGui.
#include <d3dcompiler.h>
#include <wrl/client.h>
#include <array>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <iterator>
#include <sstream>
#include <stdexcept>
#include <string>

int wmain(int argc, wchar_t** argv)
{
    try {
        if (argc != 3) throw std::runtime_error("Usage: NcmaGuiShaderCompiler <source-directory> <output-header>");
        const std::filesystem::path sourceDirectory(argv[1]), destination(argv[2]);
        struct Shader { const char* file; const char* symbol; const char* profile; };
        constexpr std::array shaders{
            Shader{"GuiVertex.hlsl", "NcmaGuiVertexBytecode", "vs_4_0"},
            Shader{"GuiImage.hlsl", "NcmaGuiImageBytecode", "ps_4_0"}
        };
        std::ostringstream header;
        header << "// Generated by NcmaGuiShaderCompiler; edit the HLSL inputs, not this file.\n#pragma once\n";
        for (const auto& shader : shaders) {
            const auto path = sourceDirectory / shader.file;
            const auto size = std::filesystem::file_size(path);
            if (size == 0 || size > 1024 * 1024) throw std::runtime_error("Invalid bounded shader input");
            std::ifstream input(path, std::ios::binary);
            if (!input) throw std::runtime_error("Cannot open shader input");
            const std::string source{std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>()};
            if (input.bad() || source.size() != size) throw std::runtime_error("Incomplete shader input");
            Microsoft::WRL::ComPtr<ID3DBlob> code, errors;
            // Same entry/profile/flags as the former runtime path; no includes,
            // macros, runtime specialization, debug flags or changed optimization.
            const HRESULT result = D3DCompile(source.data(), source.size(), nullptr, nullptr, nullptr,
                "main", shader.profile, 0, 0, &code, &errors);
            if (errors && errors->GetBufferSize() != 0) {
                std::cerr << shader.file << ": " << static_cast<const char*>(errors->GetBufferPointer()) << '\n';
                throw std::runtime_error("Shader diagnostics are fatal (including warnings)");
            }
            if (FAILED(result) || !code || code->GetBufferSize() == 0)
                throw std::runtime_error("Shader compilation failed");
            header << "static const unsigned char " << shader.symbol << "[] = {\n";
            const auto* bytes = static_cast<const unsigned char*>(code->GetBufferPointer());
            for (size_t i = 0; i < code->GetBufferSize(); ++i) {
                header << static_cast<unsigned>(bytes[i]) << ',';
                if (i % 24 == 23) header << '\n';
            }
            header << "\n};\n";
        }
        // Do not touch an earlier artifact until both compiles succeed.
        // A failed/partial output write fails the build; never use stale bytecode.
        std::ofstream output(destination, std::ios::binary | std::ios::trunc);
        if (!output) throw std::runtime_error("Cannot create generated shader header");
        output << header.str();
        output.close();
        if (!output) throw std::runtime_error("Cannot finish generated shader header");
        std::cout << "Compiled 2 fixed GUI shaders (vs_4_0/ps_4_0, flags=0)\n";
        return 0;
    }
    catch (const std::exception& e) {
        std::cerr << e.what() << '\n';
        return 1;
    }
}
